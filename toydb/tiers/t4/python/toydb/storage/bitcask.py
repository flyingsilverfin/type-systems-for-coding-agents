P = ParamSpec("P")
T = TypeVar("T")

logger = logging.getLogger(__name__)


def io_result(function: Callable[P, T]) -> Callable[P, T]:
    """Converts OS and IO errors raised by the function into `Error.IO`, like
    Rust's `?` does for `std::io::Error` via `From`."""

    @functools.wraps(function)
    def wrapper(*args: P.args, **kwargs: P.kwargs) -> T:
        try:
            return function(*args, **kwargs)
        except EOFError as error:
            raise Error.IO(str(error)) from error
        except OSError as error:
            raise Error.from_exception(error) from error

    return wrapper


def read_exact(reader: BinaryIO | io.RawIOBase, length: int) -> bytes:
    """Reads exactly the given number of bytes, like Rust's `Read::read_exact`.
    Raises EOFError if the reader ends before that."""
    buffer = bytearray()
    while len(buffer) < length:
        chunk = reader.read(length - len(buffer))
        if not chunk:
            raise EOFError("failed to fill whole buffer")
        buffer += chunk
    return bytes(buffer)


@dataclass(frozen=True)
class ValueLocation:
    """The location of a value in the log file."""

    offset: int
    length: int

    def end(self) -> int:
        return self.offset + self.length


type KeyDir = BTreeMap[bytes, ValueLocation]
"""Maps keys to a value's location in the log file."""


class BitCask(Engine):
    """A very simple variant of BitCask, itself a simple log-structured key-value
    engine used e.g. by the Riak database. This is not compatible with BitCask
    databases generated by other implementations. See:
    <https://riak.com/assets/bitcask-intro.pdf>

    BitCask writes key-value pairs to an append-only log file, and keeps a
    mapping of keys to file offsets in memory. All live keys must fit in memory.
    Deletes write a tombstone value to the log file. To remove old garbage
    (deleted or replaced keys), logs can be compacted by writing new logs
    containing only live data, dropping replaced values and tombstones.

    This implementation is significantly simpler than standard BitCask:

    * Instead of writing multiple fixed-size log files, it uses a single
      append-only log file of arbitrary size. This increases the compaction
      volume, since the entire log file must be rewritten on every compaction.
      It can also exceed the filesystem's file size limit. However, toyDB
      databases are expected to be small.

    * Compactions lock the database for reads and writes. This is ok since toyDB
      only compacts during node startup and files are expected to be small.

    * Hint files are not used, the log itself is scanned when opened to
      build the keydir. Hint files only omit values, and toyDB values are
      expected to be small, so the hint files would be nearly as large as
      the compacted log files themselves.

    * Log entries don't contain timestamps or checksums.

    The structure of an encoded log entry is:

    1. Key length as big-endian u32 [4 bytes].
    2. Value length as big-endian i32, or -1 for tombstones [4 bytes].
    3. Key as raw bytes [<= 2 GB].
    4. Value as raw bytes [<= 2 GB].
    """

    FSYNC: ClassVar[bool] = True
    """Whether flush() fsyncs the log file. The Rust tests compile this out
    (`#[cfg(not(test))]`) to speed them up, and the Python tests do the same by
    setting this to False."""

    def __init__(self, path: Path) -> None:
        """Opens or creates a BitCask database in the given file."""
        path = Path(path)
        self.log: Log = Log(path)
        """The current append-only log file."""
        self.keydir: KeyDir = self.log.build_keydir()
        """Maps keys to a value's offset and length in the log."""
        logger.info("Opened %s with %s live keys", path, len(self.keydir))

    @classmethod
    def new(cls, path: Path) -> "BitCask":
        """Opens or creates a BitCask database in the given file."""
        return cls(path)

    @classmethod
    def new_maybe_compact(
        cls, path: Path, garbage_min_fraction: float, garbage_min_bytes: int
    ) -> "BitCask":
        """Opens a BitCask database, and automatically compacts it if the amount
        of garbage exceeds the given ratio and byte size when opened."""
        engine = cls.new(path)

        status = engine.status()
        total_size = status.disk_size
        garbage_size = status.garbage_disk_size()
        garbage_fraction = garbage_size / total_size if total_size > 0 else math.nan
        if (
            garbage_size > 0
            and garbage_size >= garbage_min_bytes
            and garbage_fraction >= garbage_min_fraction
        ):
            logger.info(
                "Compacting %s to remove %.0f%% garbage (%.1f MB out of %.1f MB)",
                engine.log.path,
                garbage_fraction * 100.0,
                garbage_size / 1024.0 / 1024.0,
                total_size / 1024.0 / 1024.0,
            )
            engine.compact()
            logger.info(
                "Compacted %s to size %.1f MB",
                engine.log.path,
                (total_size - garbage_size) / 1024.0 / 1024.0,
            )

        return engine

    def delete(self, key: bytes) -> None:
        self.log.write_entry(key, None)
        self.keydir.remove(key)

    @io_result
    def flush(self) -> None:
        if self.FSYNC:
            os.fsync(self.log.file.fileno())

    def get(self, key: bytes) -> bytes | None:
        location = self.keydir.get(key)
        if location is None:
            return None
        return self.log.read_value(location)

    def scan(self, range: Range[bytes]) -> "ScanIterator":
        return ScanIterator(self.keydir.range(range), self.log)

    def set(self, key: bytes, value: bytes) -> None:
        value_location = self.log.write_entry(key, value)
        self.keydir.insert(bytes(key), value_location)

    @io_result
    def status(self) -> Status:
        keys = len(self.keydir)
        size = sum(len(key) + value_loc.length for key, value_loc in self.keydir)
        disk_size = os.fstat(self.log.file.fileno()).st_size
        live_disk_size = size + 8 * keys  # account for length prefixes
        return Status(
            name="bitcask",
            keys=keys,
            size=size,
            disk_size=disk_size,
            live_disk_size=live_disk_size,
        )

    @io_result
    def compact(self) -> None:
        """Compacts the current log file by writing out a new log file containing
        only live keys and replacing the current file with it."""
        # Create a new temporary log file, or truncate it if it already exists.
        new_path = self.log.path.with_suffix(".new")
        new_log = Log(new_path)
        new_log.file.truncate(0)

        # Write all live entries into the new log, and generate a new KeyDir.
        new_keydir: KeyDir = BTreeMap()
        for key, value_loc in self.keydir:
            value = self.log.read_value(value_loc)
            value_loc = new_log.write_entry(key, value)
            new_keydir.insert(key, value_loc)

        # Replace the current log with the new one.
        os.rename(new_log.path, self.log.path)
        new_log.path = self.log.path

        self.log.close()
        self.log = new_log
        self.keydir = new_keydir

    def close(self) -> None:
        """Attempts to flush the file and closes the database, releasing the
        file lock. This is the equivalent of dropping the Rust engine, and
        also happens when the engine is garbage collected."""
        if self.log.file.closed:
            return
        try:
            self.flush()
        except Error as error:
            logger.error("failed to flush file: %s", error)
        self.log.close()

    def __del__(self) -> None:
        # The log doesn't exist if opening it failed. Never raise from a
        # finalizer, e.g. during interpreter shutdown.
        try:
            if hasattr(self, "log"):
                self.close()
        except Exception:
            pass


class ScanIterator(engine.ScanIterator):
    """A scan iterator over a key range, which reads values from the log."""

    def __init__(self, inner: MapRange[bytes, ValueLocation], log: "Log") -> None:
        self.inner = inner
        self.log = log

    def map(self, item: tuple[bytes, ValueLocation]) -> tuple[bytes, bytes]:
        key, value_loc = item
        return key, self.log.read_value(value_loc)

    def __next__(self) -> tuple[bytes, bytes]:
        return self.map(next(self.inner))

    def next_back(self) -> tuple[bytes, bytes]:
        return self.map(self.inner.next_back())


class Log:
    """A BitCask append-only log file, containing a sequence of key/value
    entries encoded as follows;

    1. Key length as big-endian u32 [4 bytes].
    2. Value length as big-endian i32, or -1 for tombstones [4 bytes].
    3. Key as raw bytes [<= 2 GB].
    4. Value as raw bytes [<= 2 GB].
    """

    @io_result
    def __init__(self, path: Path) -> None:
        """Opens a log file, or creates one if it does not exist. Takes out an
        exclusive lock on the file until it is closed, or errors if the lock is
        already held."""
        path.parent.mkdir(parents=True, exist_ok=True)
        fd = os.open(path, os.O_RDWR | os.O_CREAT, 0o666)
        file = io.FileIO(fd, "r+")
        try:
            fcntl.flock(file.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError:
            file.close()
            raise Error.IO(f"file {debug_str(str(path))} is already is use") from None
        except OSError:
            file.close()
            raise
        self.file: io.FileIO = file
        """The open log file. Unbuffered."""
        self.path: Path = path
        """Path to the log file."""

    def close(self) -> None:
        """Closes the log file, releasing the file lock."""
        self.file.close()

    @io_result
    def build_keydir(self) -> KeyDir:
        """Builds a keydir by scanning the log file. If an incomplete entry is
        encountered, it is assumed to be caused by an incomplete write operation
        and the remainder of the file is truncated."""
        keydir: KeyDir = BTreeMap()
        file_len = os.fstat(self.file.fileno()).st_size
        r = io.BufferedReader(self.file)
        offset = r.seek(0)

        def read_entry() -> tuple[bytes, ValueLocation | None]:
            """Reads the next entry from the file, returning the key and value
            location, or None for tombstones. Raises EOFError if the entry is
            incomplete."""
            nonlocal offset

            # Read the key length: 4-byte u32.
            key_len = int.from_bytes(read_exact(r, 4), "big")

            # Read the value length: 4-byte i32, -1 for tombstones.
            value_len = int.from_bytes(read_exact(r, 4), "big", signed=True)
            value_loc = None
            if value_len >= 0:
                value_loc = ValueLocation(offset=offset + 8 + key_len, length=value_len)

            # Read the key.
            key = read_exact(r, key_len)

            # Skip past the value.
            if value_loc is not None:
                if value_loc.end() > file_len:
                    raise EOFError("value extends beyond end of file")
                r.seek(value_loc.length, os.SEEK_CUR)

            # Update the file offset.
            offset += 8 + key_len + (value_loc.length if value_loc is not None else 0)

            return key, value_loc

        try:
            while offset < file_len:
                # Update the keydir with the entry.
                try:
                    key, value_loc = read_entry()
                except EOFError:
                    # If an incomplete entry was found at the end of the file,
                    # assume an incomplete write and truncate the file.
                    logger.error("Found incomplete entry at offset %s, truncating file", offset)
                    self.file.truncate(offset)
                    break
                if value_loc is not None:
                    keydir.insert(key, value_loc)
                else:
                    keydir.remove(key)
        finally:
            r.detach()  # don't close the file with the reader

        return keydir

    @io_result
    def read_value(self, location: ValueLocation) -> bytes:
        """Reads a value from the log file at the given location."""
        self.file.seek(location.offset)
        return read_exact(self.file, location.length)

    @io_result
    def write_entry(self, key: bytes, value: bytes | None) -> ValueLocation:
        """Appends a key/value entry to the log file, using a None value for
        tombstones. It returns the location of the entry's value in the log, for
        use with the `KeyDir`."""
        offset = self.file.seek(0, os.SEEK_END)
        entry = bytearray()

        # Key length: 4-byte u32.
        entry += len(key).to_bytes(4, "big")

        # Value length: 4-byte i32, -1 for tombstones.
        entry += (len(value) if value is not None else -1).to_bytes(4, "big", signed=True)

        # The actual key and value.
        entry += key
        entry += value if value is not None else b""

        # Write the entry in one go, like a BufWriter sized for the entry.
        view = memoryview(entry)
        while view:
            view = view[self.file.write(view) :]

        # Translate the entry location into a value location.
        return ValueLocation(
            offset=offset + 8 + len(key),
            length=len(value) if value is not None else 0,
        )
