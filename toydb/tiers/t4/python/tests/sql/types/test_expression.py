def build(expr: ast.Expression) -> Expression:
    """Builds a constant expression from an AST expression, like the Rust
    `Planner::build_expression` with an empty scope."""
    match expr:
        case ast.Expression.Literal(literal):
            match literal:
                case ast.Literal.Null():
                    return k(Value.Null())
                case ast.Literal.Boolean(b):
                    return k(Value.Boolean(b))
                case ast.Literal.Integer(i):
                    return k(Value.Integer(i))
                case ast.Literal.Float(f):
                    return k(Value.Float(f))
                case ast.Literal.String(s):
                    return k(Value.String(s))
                case _:
                    raise AssertionError(f"unknown literal {literal!r}")
        case ast.Expression.Function("sqrt", [arg]):
            return Expression.SquareRoot(build(arg))
        case ast.Expression.Operator(op):
            match op:
                case ast.Operator.And(lhs, rhs):
                    return Expression.And(build(lhs), build(rhs))
                case ast.Operator.Not(inner):
                    return Expression.Not(build(inner))
                case ast.Operator.Or(lhs, rhs):
                    return Expression.Or(build(lhs), build(rhs))
                case ast.Operator.Equal(lhs, rhs):
                    return Expression.Equal(build(lhs), build(rhs))
                case ast.Operator.GreaterThan(lhs, rhs):
                    return Expression.GreaterThan(build(lhs), build(rhs))
                case ast.Operator.GreaterThanOrEqual(lhs, rhs):
                    return Expression.Or(
                        Expression.GreaterThan(build(lhs), build(rhs)),
                        Expression.Equal(build(lhs), build(rhs)),
                    )
                case ast.Operator.Is(inner, ast.Literal.Null()):
                    return Expression.Is(build(inner), Value.Null())
                case ast.Operator.Is(inner, ast.Literal.Float(f)):
                    return Expression.Is(build(inner), Value.Float(f))
                case ast.Operator.IsNot(inner, literal):
                    return Expression.Not(build(ast.Expression.Operator(ast.Operator.Is(inner, literal))))
                case ast.Operator.LessThan(lhs, rhs):
                    return Expression.LessThan(build(lhs), build(rhs))
                case ast.Operator.LessThanOrEqual(lhs, rhs):
                    return Expression.Or(
                        Expression.LessThan(build(lhs), build(rhs)),
                        Expression.Equal(build(lhs), build(rhs)),
                    )
                case ast.Operator.Like(lhs, rhs):
                    return Expression.Like(build(lhs), build(rhs))
                case ast.Operator.NotEqual(lhs, rhs):
                    return Expression.Not(Expression.Equal(build(lhs), build(rhs)))
                case ast.Operator.Add(lhs, rhs):
                    return Expression.Add(build(lhs), build(rhs))
                case ast.Operator.Divide(lhs, rhs):
                    return Expression.Divide(build(lhs), build(rhs))
                case ast.Operator.Exponentiate(lhs, rhs):
                    return Expression.Exponentiate(build(lhs), build(rhs))
                case ast.Operator.Factorial(inner):
                    return Expression.Factorial(build(inner))
                case ast.Operator.Identity(inner):
                    return Expression.Identity(build(inner))
                case ast.Operator.Remainder(lhs, rhs):
                    return Expression.Remainder(build(lhs), build(rhs))
                case ast.Operator.Multiply(lhs, rhs):
                    return Expression.Multiply(build(lhs), build(rhs))
                case ast.Operator.Negate(inner):
                    return Expression.Negate(build(inner))
                case ast.Operator.Subtract(lhs, rhs):
                    return Expression.Subtract(build(lhs), build(rhs))
                case _:
                    raise AssertionError(f"unknown operator {op!r}")
        case _:
            raise AssertionError(f"unsupported expression {expr!r}")


def evaluate(expr: Expression, row: list[Value] | None = None) -> str:
    """Evaluates an expression, formatting the result, error or panic."""
    try:
        value = expr.evaluate(row)
    except Error as error:
        return f"Err: {error}"
    except Panic:
        return "PANIC"
    return f"{value} {debug(value)}"


def parse(expr: str) -> Expression:
    """Parses and builds a constant expression."""
    return build(Parser.parse_expr(expr))


class TestExpression(unittest.TestCase):
    maxDiff = None

    def test_cases(self) -> None:
        node = Nothing()
        for input, debugged, display, result, cnf, nnf, cnf_vec in CASES:
            with self.subTest(input=input):
                expr = parse(input)
                self.assertEqual(debug(expr), debugged)
                self.assertEqual(str(expr.display(node)), display)
                self.assertEqual(evaluate(expr), result)
                self.assertEqual(str(expr.into_cnf().display(node)), cnf)
                self.assertEqual(str(expr.into_nnf().display(node)), nnf)
                self.assertEqual(debug(expr.into_cnf_vec()), cnf_vec)
                # CNF and NNF must not change the result.
                self.assertEqual(evaluate(expr.into_cnf()), result)
                self.assertEqual(evaluate(expr.into_nnf()), result)

    def test_format(self) -> None:
        node = Nothing()
        for expr, (display, debugged, _) in zip(EXPRESSIONS, FORMATS, strict=True):
            with self.subTest(expr=expr):
                self.assertEqual(str(expr.display(node)), display)
                self.assertEqual(debug(expr), debugged)
                self.assertEqual(repr(expr), debugged)

    def test_display_labels(self) -> None:
        node = Labels(Label.Unqualified("id"), Label.Qualified("t", "name"), Label.None_())
        expr = Expression.And(
            Expression.Equal(c(0), k(Value.Integer(1))),
            Expression.Or(Expression.Like(c(1), k(Value.String("a%"))), Expression.Not(c(2))),
        )
        self.assertEqual(str(expr.display(node)), "id = 1 AND (t.name LIKE 'a%' OR NOT #2)")

    def test_encoding(self) -> None:
        for expr, (_, _, encoded) in zip(EXPRESSIONS, FORMATS, strict=True):
            with self.subTest(expr=expr):
                self.assertEqual(bincode.serialize(expr).hex(), encoded)
                self.assertEqual(bincode.deserialize(Expression, bytes.fromhex(encoded)), expr)
        with self.assertRaises(Error):
            bincode.deserialize(Expression, b"\x14")

    def test_evaluate_row(self) -> None:
        row = [Value.Integer(3), Value.Float(1.5), Value.Null()]
        self.assertEqual(evaluate(c(0), row), "3 Integer(3)")
        self.assertEqual(evaluate(Expression.Add(c(0), c(1)), row), "4.5 Float(4.5)")
        self.assertEqual(evaluate(Expression.Is(c(2), Value.Null()), row), "TRUE Boolean(true)")
        self.assertEqual(evaluate(Expression.Is(c(0), Value.Null()), row), "FALSE Boolean(false)")
        # Invalid column references and IS values panic.
        self.assertEqual(evaluate(c(3), row), "PANIC")
        self.assertEqual(evaluate(c(0), None), "PANIC")
        self.assertEqual(evaluate(Expression.Is(c(0), Value.Integer(1)), row), "PANIC")

    def test_walk(self) -> None:
        expr = parse("1 + 2 * 3 = 7 AND NOT sqrt(4) IS NULL")
        visited: list[str] = []

        def visit(expr: Expression) -> bool:
            visited.append(type(expr).__name__)
            return True

        self.assertTrue(expr.walk(visit))
        self.assertEqual(
            " ".join(visited),
            "And Equal Add Constant Multiply Constant Constant Constant Not Is SquareRoot Constant",
        )

        # Returning false halts the walk.
        visited.clear()
        self.assertFalse(expr.walk(lambda e: visit(e) and not isinstance(e, Expression.Multiply)))
        self.assertEqual(" ".join(visited), "And Equal Add Constant Multiply")

    def test_contains(self) -> None:
        expr = parse("1 + 2 * 3 = 7 AND NOT sqrt(4) IS NULL")
        self.assertTrue(expr.contains(lambda e: isinstance(e, Expression.SquareRoot)))
        self.assertTrue(expr.contains(lambda e: e == k(Value.Integer(7))))
        self.assertFalse(expr.contains(lambda e: isinstance(e, Expression.Column)))
        self.assertFalse(expr.contains(lambda e: e == k(Value.Integer(8))))

    def test_transform(self) -> None:
        node = Nothing()
        expr = parse("1 + 2 * 3 = 7 AND NOT sqrt(4) IS NULL")
        order: list[str] = []

        def before(expr: Expression) -> Expression:
            order.append(f"<{type(expr).__name__}")
            return expr

        def after(expr: Expression) -> Expression:
            order.append(f"{type(expr).__name__}>")
            return expr

        self.assertEqual(expr.transform(before, after), expr)
        self.assertEqual(
            " ".join(order),
            "<And <Equal <Add <Constant Constant> <Multiply <Constant Constant> <Constant "
            "Constant> Multiply> Add> <Constant Constant> Equal> <Not <Is <SquareRoot <Constant "
            "Constant> SquareRoot> Is> Not> And>",
        )

        # Transformations return a new expression, leaving the original as is.
        def increment(expr: Expression) -> Expression:
            match expr:
                case Expression.Constant(Value.Integer(i)):
                    return k(Value.Integer(i + 1))
                case _:
                    return expr

        transformed = expr.transform(increment, lambda e: e)
        self.assertEqual(str(transformed.display(node)), "2 + 3 * 4 = 8 AND NOT sqrt(5) IS NULL")
        self.assertEqual(str(expr.display(node)), "1 + 2 * 3 = 7 AND NOT sqrt(4) IS NULL")

        # Errors are propagated.
        def fail(expr: Expression) -> Expression:
            raise errinput("failed")

        with self.assertRaises(Error):
            expr.transform(lambda e: e, fail)

    def test_and_vec(self) -> None:
        self.assertIsNone(Expression.and_vec([]))
        self.assertEqual(Expression.and_vec([c(0)]), c(0))
        self.assertEqual(
            Expression.and_vec([c(0), c(1), c(2)]),
            Expression.And(Expression.And(c(0), c(1)), c(2)),
        )

    def test_column_lookup(self) -> None:
        one, two, null = Value.Integer(1), Value.Integer(2), Value.Null()
        nan = Value.Float(math.nan)
        equal, or_, is_ = Expression.Equal, Expression.Or, Expression.Is
        cases: list[tuple[Expression, int | None, list[Value]]] = [
            (equal(c(1), k(one)), 1, [one]),
            (equal(k(one), c(1)), 1, [one]),
            (equal(c(1), k(null)), 1, []),
            (equal(c(1), k(nan)), 1, []),
            (is_(c(1), null), 1, [null]),
            (is_(c(1), nan), 1, [nan]),
            (or_(equal(c(1), k(one)), equal(k(two), c(1))), 1, [one, two]),
            (or_(or_(equal(c(1), k(one)), is_(c(1), null)), equal(c(1), k(two))), 1, [one, null, two]),
            (or_(equal(c(1), k(one)), equal(c(2), k(two))), None, []),
            (or_(equal(c(1), k(one)), c(1)), None, []),
            (equal(c(1), c(1)), None, []),
            (equal(k(one), k(one)), None, []),
            (is_(k(one), null), None, []),
            (Expression.And(equal(c(1), k(one)), equal(c(1), k(two))), None, []),
            (Expression.GreaterThan(c(1), k(one)), None, []),
            (c(1), None, []),
        ]
        for expr, column, values in cases:
            with self.subTest(expr=expr):
                self.assertEqual(expr.is_column_lookup(), column)
                if column is not None:
                    self.assertEqual(expr.into_column_values(column), values)
                    with self.assertRaises(AssertionError):
                        expr.into_column_values(column + 1)
                else:
                    with self.assertRaises(AssertionError):
                        expr.into_column_values(1)

    def test_replace_column(self) -> None:
        expr = Expression.Add(c(0), Expression.Multiply(c(1), c(0)))
        self.assertEqual(
            expr.replace_column(0, 2), Expression.Add(c(2), Expression.Multiply(c(1), c(2)))
        )
        self.assertEqual(expr.replace_column(3, 2), expr)

    def test_shift_column(self) -> None:
        expr = Expression.Add(c(2), Expression.Multiply(c(3), k(Value.Integer(1))))
        self.assertEqual(
            expr.shift_column(2),
            Expression.Add(c(4), Expression.Multiply(c(5), k(Value.Integer(1)))),
        )
        self.assertEqual(
            expr.shift_column(-2),
            Expression.Add(c(0), Expression.Multiply(c(1), k(Value.Integer(1)))),
        )

    def test_equality(self) -> None:
        """Expressions compare by value, using Value equality."""
        self.assertEqual(parse("1 + 2"), parse("1 + 2"))
        self.assertNotEqual(parse("1 + 2"), parse("2 + 1"))
        self.assertNotEqual(parse("1 + 2"), parse("1 - 2"))
        self.assertEqual(k(Value.Float(math.nan)), k(Value.Float(math.nan)))
        self.assertEqual(Expression.from_value(Value.Null()), k(Value.Null()))
        self.assertEqual(len({parse("1 + 2"), parse("1 + 2"), parse("1 + 3")}), 2)


