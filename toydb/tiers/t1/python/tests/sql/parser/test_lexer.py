def lex(input: str) -> str:
    """Lexes the input, formatting the tokens and any error."""
    output: list[str] = []
    lexer = Lexer(input)
    while True:
        try:
            token = next(lexer, None)
        except Error as error:
            output.append(f"Err: {error}")
            break
        if token is None:
            break
        output.append(f"{debug(token)}={token}")
    return " ".join(output).replace("\n", "\\n")


class TestLexer(unittest.TestCase):
    def test_tokens(self) -> None:
        for input, expect, _ in CASES:
            with self.subTest(input=input):
                self.assertEqual(lex(input), expect)

    def test_is_ident(self) -> None:
        for input, _, expect in CASES:
            with self.subTest(input=input):
                self.assertEqual(is_ident(input), expect)

    def test_iterator(self) -> None:
        """The lexer is a regular iterator when the input is valid."""
        tokens = list(Lexer("SELECT a, 1 FROM t"))
        self.assertEqual(
            tokens,
            [
                Token.Keyword(Keyword.Select),
                Token.Ident("a"),
                Token.Comma(),
                Token.Number("1"),
                Token.Keyword(Keyword.From),
                Token.Ident("t"),
            ],
        )

    def test_error_not_consumed(self) -> None:
        """An unexpected character is not consumed, so the error repeats."""
        lexer = Lexer("a $")
        self.assertEqual(next(lexer), Token.Ident("a"))
        for _ in range(3):
            with self.assertRaises(Error) as cm:
                next(lexer)
            self.assertEqual(str(cm.exception), "invalid input: unexpected character $")

    def test_keywords(self) -> None:
        """All keywords are lexed case-insensitively, display as uppercase,
        and can't be used as identifiers unless quoted."""
        self.assertEqual(len(Keyword), 66)
        for keyword in Keyword:
            with self.subTest(keyword=keyword):
                self.assertEqual(Keyword.try_from(keyword.value), keyword)
                self.assertEqual(str(keyword), keyword.value.upper())
                self.assertEqual(debug(keyword).lower(), keyword.value)
                for input in (keyword.value, keyword.value.upper(), keyword.value.title()):
                    self.assertEqual(list(Lexer(input)), [Token.Keyword(keyword)])
                    self.assertFalse(is_ident(input))
                self.assertEqual(list(Lexer(f'"{keyword.value}"')), [Token.Ident(keyword.value)])
        self.assertIsNone(Keyword.try_from("foo"))
        self.assertEqual(debug(Keyword.True_), "True")
        self.assertEqual(debug(Keyword.NaN), "NaN")
        self.assertEqual(str(Keyword.NaN), "NAN")


