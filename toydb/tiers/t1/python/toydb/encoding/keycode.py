"""Keycode is a lexicographical order-preserving binary encoding for use with
keys in key/value stores. It is designed for simplicity, not efficiency
(i.e. it does not use varints or other compression methods).

Ordering is important because it allows limited scans across specific parts
of the keyspace, e.g. scanning an individual table or using an index range
predicate like `WHERE id < 100`. It also avoids sorting in some cases where
the keys are already in the desired order, e.g. in the Raft log.

The encoding is not self-describing: the caller must provide a concrete type
to decode into, and the binary key must conform to its structure.

Keycode supports a subset of primitive data types, encoded as follows:

* `bool`: `0x00` for `false`, `0x01` for `true`.
* `u64`: big-endian binary representation.
* `i64`: big-endian binary, sign bit flipped.
* `f64`: big-endian binary, sign bit flipped, all flipped if negative.
* `bytes`: `0x00` escaped as `0x00ff`, terminated with `0x0000`.
* `str`: like `bytes`.
* Sequences: concatenation of contained elements, with no other structure.
* Enum: the variant's index as `u8`, then the content sequence.
* `toydb.sql.types.Value`: like any other enum.

The canonical key representation is an enum, i.e. a class hierarchy which
implements `serialize` and `deserialize` as described in
`toydb.encoding.serde`.
"""

import struct
from collections.abc import Callable, Hashable
from typing import NoReturn, TypeVar

from toydb.encoding import serde
from toydb.error import Error, Panic, errdata
from toydb.fmt import debug_bytes_hex, display_utf8_error
from toydb.ops import Bound, Range

T = TypeVar("T")
K = TypeVar("K", bound=Hashable)
V = TypeVar("V")


def serialize(key: T, serde: serde.Serde[T] | None = None) -> bytes:
    """Serializes a key to a binary Keycode representation. The serde
    describes the key's Rust type, and defaults to the key's class (which must
    then implement `serialize`).

    In the common case, the encoded key is borrowed for a storage engine call
    and then thrown away. We could avoid a bunch of allocations by taking a
    reusable byte vector to encode into and return a reference to it, but we
    keep it simple.
    """
    serializer = Serializer()
    # Panic on failure, as this is a problem with the data structure.
    try:
        if serde is not None:
            serde.serialize(key, serializer)
        else:
            key.serialize(serializer)  # type: ignore[attr-defined]
    except (Error, OverflowError, struct.error) as error:
        raise Panic(f"key must be serializable: {error!r}") from error
    return bytes(serializer.output)


def deserialize(serde: serde.Serde[T], input: bytes) -> T:
    """Deserializes a key of the given type from a binary Keycode
    representation."""
    deserializer = Deserializer.from_bytes(input)
    t = serde.deserialize(deserializer)
    if deserializer.input:
        raise errdata(
            f"unexpected trailing bytes {debug_bytes_hex(deserializer.input)} "
            f"at end of key {debug_bytes_hex(input)}"
        )
    return t


def prefix_range(prefix: bytes) -> Range[bytes]:
    """Generates a key range for a key prefix, used e.g. for prefix scans.

    The exclusive end bound is generated by adding 1 to the value of the last
    byte. If the last byte(s) is 0xff (so adding 1 would overflow), we instead
    find the latest non-0xff byte, increment that, and truncate the rest. If all
    bytes are 0xff, we scan to the end of the range, since there can't be other
    prefixes after it.
    """
    start: Bound[bytes] = Bound.Included(bytes(prefix))
    end: Bound[bytes] = Bound.Unbounded()
    for i in reversed(range(len(prefix))):
        if prefix[i] != 0xFF:
            end = Bound.Excluded(bytes(prefix[:i]) + bytes([prefix[i] + 1]))
            break
    return (start, end)


def _unimplemented() -> NoReturn:
    """Panics on unsupported data types, like Rust's `unimplemented!()`."""
    raise NotImplementedError("not implemented")


class Serializer(serde.Serializer):
    """Serializes keys as binary byte vectors."""

    def __init__(self) -> None:
        self.output = bytearray()

    def serialize_bool(self, v: bool) -> None:
        """bool simply uses 1 for true and 0 for false."""
        self.output.append(1 if v else 0)

    def serialize_i8(self, v: int) -> None:
        _unimplemented()

    def serialize_i16(self, v: int) -> None:
        _unimplemented()

    def serialize_i32(self, v: int) -> None:
        _unimplemented()

    def serialize_i64(self, v: int) -> None:
        """i64 uses the big-endian two's complement encoding, but flips the
        left-most sign bit such that negative numbers are ordered before
        positive numbers.

        The relative ordering of the remaining bits is already correct: -1, the
        largest negative integer, is encoded as 01111111...11111111, ordered
        after all other negative integers but before positive integers.
        """
        encoded = bytearray(v.to_bytes(8, "big", signed=True))
        encoded[0] ^= 1 << 7  # flip sign bit
        self.output += encoded

    def serialize_u8(self, v: int) -> None:
        _unimplemented()

    def serialize_u16(self, v: int) -> None:
        _unimplemented()

    def serialize_u32(self, v: int) -> None:
        _unimplemented()

    def serialize_u64(self, v: int) -> None:
        """u64 simply uses the big-endian encoding."""
        self.output += v.to_bytes(8, "big")

    def serialize_f64(self, v: float) -> None:
        """f64 is encoded in big-endian IEEE 754 form, but it flips the sign bit to
        order positive numbers after negative numbers, and also flips all other
        bits for negative numbers to order them from smallest to largest. NaN is
        ordered at the end.
        """
        encoded = bytearray(struct.pack(">d", v))
        if encoded[0] >> 7 == 0:
            encoded[0] ^= 1 << 7  # positive, flip sign bit
        else:
            encoded = bytearray(b ^ 0xFF for b in encoded)  # negative, flip all bits
        self.output += encoded

    def serialize_str(self, v: str) -> None:
        """Strings are encoded like bytes."""
        self.serialize_bytes(v.encode())

    def serialize_bytes(self, v: bytes) -> None:
        """Byte slices are terminated by 0x0000, escaping 0x00 as 0x00ff. This
        ensures that we can detect the end, and that for two overlapping slices,
        the shorter one orders before the longer one.

        We can't use e.g. length prefix encoding, since it doesn't sort correctly.
        """
        self.output += bytes(v).replace(b"\x00", b"\x00\xff")
        self.output += b"\x00\x00"

    def serialize_none(self) -> None:
        _unimplemented()

    def serialize_some(self) -> None:
        _unimplemented()

    def serialize_unit(self) -> None:
        _unimplemented()

    def serialize_unit_variant(self, index: int) -> None:
        """Enum variants are serialized using their index, as a single byte."""
        if not 0 <= index <= 0xFF:
            raise errdata("out of range integral type conversion attempted")
        self.output.append(index)

    def serialize_newtype_variant(self, index: int) -> None:
        """Newtype variants are serialized using the variant index and inner type."""
        self.serialize_unit_variant(index)

    def serialize_tuple_variant(self, index: int) -> None:
        """Tuple variants are serialized using the variant index and the
        concatenation of the serialized elements."""
        self.serialize_unit_variant(index)

    def serialize_struct_variant(self, index: int) -> None:
        _unimplemented()

    def serialize_seq(self, len: int) -> None:
        """Sequences are serialized as the concatenation of the serialized elements."""

    def serialize_tuple(self, len: int) -> None:
        """Tuples are serialized as the concatenation of the serialized elements."""

    def serialize_map(self, len: int) -> None:
        _unimplemented()

    def serialize_struct(self) -> None:
        _unimplemented()


class Deserializer(serde.Deserializer):
    """Deserializes keys from byte slices into a given type. The format is not
    self-describing, so the caller must provide a concrete type to deserialize
    into."""

    def __init__(self, input: bytes) -> None:
        self.input = input

    @classmethod
    def from_bytes(cls, input: bytes) -> "Deserializer":
        """Creates a deserializer for a byte slice."""
        return cls(bytes(input))

    def take_bytes(self, n: int) -> bytes:
        """Chops off and returns the next n bytes of the byte slice, or errors if
        there aren't enough bytes left."""
        if len(self.input) < n:
            raise errdata(
                f"insufficient bytes, expected {n} bytes for {debug_bytes_hex(self.input)}"
            )
        taken = self.input[:n]
        self.input = self.input[n:]
        return taken

    def decode_next_bytes(self) -> bytes:
        """Decodes and chops off the next encoded byte slice."""
        decoded = bytearray()
        position = 0
        while True:
            end = self.input.find(b"\x00", position)
            if end < 0:
                raise errdata("unexpected end of input")
            decoded += self.input[position:end]
            match self.input[end + 1 : end + 2]:
                case b"\x00":  # terminator
                    self.input = self.input[end + 2 :]
                    return bytes(decoded)
                case b"\xff":  # escaped 0x00
                    decoded.append(0x00)
                    position = end + 2
                case _:
                    raise errdata("invalid escape sequence")

    def deserialize_bool(self) -> bool:
        match self.take_bytes(1)[0]:
            case 0x00:
                return False
            case 0x01:
                return True
            case b:
                raise errdata(f"invalid boolean value {b}")

    def deserialize_i8(self) -> int:
        _unimplemented()

    def deserialize_i16(self) -> int:
        _unimplemented()

    def deserialize_i32(self) -> int:
        _unimplemented()

    def deserialize_i64(self) -> int:
        encoded = bytearray(self.take_bytes(8))
        encoded[0] ^= 1 << 7  # flip sign bit
        return int.from_bytes(encoded, "big", signed=True)

    def deserialize_u8(self) -> int:
        _unimplemented()

    def deserialize_u16(self) -> int:
        _unimplemented()

    def deserialize_u32(self) -> int:
        _unimplemented()

    def deserialize_u64(self) -> int:
        return int.from_bytes(self.take_bytes(8), "big")

    def deserialize_f64(self) -> float:
        encoded = bytearray(self.take_bytes(8))
        if encoded[0] >> 7 == 0:
            encoded = bytearray(b ^ 0xFF for b in encoded)  # negative, flip all bits
        else:
            encoded[0] ^= 1 << 7  # positive, flip sign bit
        return struct.unpack(">d", encoded)[0]

    def deserialize_str(self) -> str:
        decoded = self.decode_next_bytes()
        try:
            return decoded.decode()
        except UnicodeDecodeError as error:
            raise errdata(display_utf8_error(error)) from error

    def deserialize_bytes(self) -> bytes:
        return self.decode_next_bytes()

    def deserialize_option(self) -> bool:
        _unimplemented()

    def deserialize_unit(self) -> None:
        _unimplemented()

    def deserialize_enum(self) -> int:
        """Enum variants are deserialized by their index."""
        return self.take_bytes(1)[0]

    def deserialize_struct_variant(self) -> None:
        _unimplemented()

    def deserialize_seq(self, element: Callable[[], T]) -> list[T]:
        """Sequences are simply deserialized until the byte slice is exhausted."""
        elements: list[T] = []
        while self.input:
            elements.append(element())
        return elements

    def deserialize_tuple(self, len: int) -> None:
        pass

    def deserialize_map(self, key: Callable[[], K], value: Callable[[], V]) -> dict[K, V]:
        _unimplemented()

    def deserialize_struct(self) -> None:
        _unimplemented()
