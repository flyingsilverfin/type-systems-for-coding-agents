def parse(statement: str) -> str:
    """Parses a statement, formatting the AST or error."""
    try:
        return debug(Parser.parse(statement)).replace("\n", "\\n")
    except Error as error:
        return f"Err: {error}".replace("\n", "\\n")


def parse_expr(expr: str) -> str:
    """Parses an expression, formatting the AST or error."""
    try:
        return debug(Parser.parse_expr(expr))
    except Error as error:
        return f"Err: {error}".replace("\n", "\\n")


class TestParser(unittest.TestCase):
    maxDiff = None

    def test_parse(self) -> None:
        for statement, expect in STATEMENTS:
            with self.subTest(statement=statement):
                self.assertEqual(parse(statement), expect)

    def test_parse_expr(self) -> None:
        for expr, expect in EXPRESSIONS:
            with self.subTest(expr=expr):
                self.assertEqual(parse_expr(expr), expect)

    def test_parse_select_expr(self) -> None:
        """Expressions parse the same way inside a SELECT statement."""
        for expr, expect in EXPRESSIONS:
            if expect.startswith("Err: ") or expect == "All":
                continue
            with self.subTest(expr=expr):
                match Parser.parse(f"SELECT {expr}"):
                    case ast.Statement.Select(select=[(parsed, None)]):
                        self.assertEqual(debug(parsed), expect)
                    case statement:
                        self.fail(f"unexpected statement {statement!r}")

    def test_ast(self) -> None:
        """The AST is made up of the expected Python objects."""
        self.assertEqual(
            Parser.parse("CREATE TABLE t (id INT PRIMARY KEY, s STRING DEFAULT 'a')"),
            ast.Statement.CreateTable(
                name="t",
                columns=[
                    ast.Column(
                        name="id",
                        datatype=DataType.Integer,
                        primary_key=True,
                        nullable=None,
                        default=None,
                        unique=False,
                        index=False,
                        references=None,
                    ),
                    ast.Column(
                        name="s",
                        datatype=DataType.String,
                        primary_key=False,
                        nullable=None,
                        default=ast.Expression.Literal(ast.Literal.String("a")),
                        unique=False,
                        index=False,
                        references=None,
                    ),
                ],
            ),
        )
        column = ast.Expression.Column
        self.assertEqual(
            Parser.parse("SELECT a, t.b AS c FROM t JOIN u ON a = 1 ORDER BY a DESC, b LIMIT 2"),
            ast.Statement.Select(
                select=[(column(None, "a"), None), (column("t", "b"), "c")],
                from_=[
                    ast.From.Join(
                        left=ast.From.Table(name="t", alias=None),
                        right=ast.From.Table(name="u", alias=None),
                        type=ast.JoinType.Inner,
                        predicate=ast.Expression.Operator(
                            ast.Operator.Equal(
                                column(None, "a"),
                                ast.Expression.Literal(ast.Literal.Integer(1)),
                            )
                        ),
                    )
                ],
                where=None,
                group_by=[],
                having=None,
                order_by=[
                    (column(None, "a"), ast.Direction.Descending),
                    (column(None, "b"), ast.Direction.Ascending),
                ],
                offset=None,
                limit=ast.Expression.Literal(ast.Literal.Integer(2)),
            ),
        )

    def test_update_set_order(self) -> None:
        """UPDATE SET columns are ordered by name, like the Rust BTreeMap."""
        match Parser.parse("UPDATE t SET c = 1, a = DEFAULT, b = 2"):
            case ast.Statement.Update(set=set):
                self.assertEqual(list(set), ["a", "b", "c"])
                self.assertIsNone(set["a"])
            case statement:
                self.fail(f"unexpected statement {statement!r}")

    def test_literals(self) -> None:
        """Literals are parsed into the expected Python values."""
        literal = ast.Expression.Literal
        self.assertEqual(Parser.parse_expr("1"), literal(ast.Literal.Integer(1)))
        self.assertEqual(Parser.parse_expr("1.5"), literal(ast.Literal.Float(1.5)))
        self.assertEqual(Parser.parse_expr("1e2"), literal(ast.Literal.Float(100.0)))
        self.assertEqual(Parser.parse_expr("'a'"), literal(ast.Literal.String("a")))
        self.assertEqual(Parser.parse_expr("true"), literal(ast.Literal.Boolean(True)))
        self.assertEqual(Parser.parse_expr("null"), literal(ast.Literal.Null()))
        self.assertEqual(Parser.parse_expr("infinity"), literal(ast.Literal.Float(math.inf)))
        self.assertEqual(Parser.parse_expr("nan"), literal(ast.Literal.Float(math.nan)))

    def test_pretty(self) -> None:
        """The AST can be formatted like Rust's `{:#?}`."""
        statement = Parser.parse("SELECT a AS b FROM t WHERE TRUE")
        expect = """\
Select {
    select: [
        (
            Column(
                None,
                "a",
            ),
            Some(
                "b",
            ),
        ),
    ],
    from: [
        Table {
            name: "t",
            alias: None,
        },
    ],
    where: Some(
        Literal(
            Boolean(
                true,
            ),
        ),
    ),
    group_by: [],
    having: None,
    order_by: [],
    offset: None,
    limit: None,
}"""
        self.assertEqual(debug(statement, pretty=True), expect)


